// Generates the module and theme registries from the folders under modules/ and themes/.
// Reads package.json only; never imports module code. Run: node tools/gen-registry.ts
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Same value as ID_RE in @dash/contract (tools/gen-registry.test.ts asserts they stay equal);
// Node cannot load the contract package directly because it is TypeScript with `.js` specifiers.
export const ID_RE = /^[a-z][a-z0-9-]{1,31}$/;

export interface GenResult {
  exitCode: 0 | 1;
  messages: string[];
}

interface Entry {
  id: string;
  name: string;
}

type Kind = 'module' | 'theme';

interface Pkg {
  name?: unknown;
  dash?: { name?: unknown };
}

function scan(rootDir: string, kind: Kind, errors: string[]): Entry[] {
  const base = path.join(rootDir, `${kind}s`);
  let dirs: string[];
  try {
    dirs = readdirSync(base).filter((d) => !d.startsWith('_') && statSync(path.join(base, d)).isDirectory());
  } catch {
    return [];
  }
  const prefix = `@dash/${kind}-`;
  const entries: Entry[] = [];
  const seen = new Map<string, string>();
  for (const dir of dirs.sort()) {
    let pkg: Pkg;
    try {
      pkg = JSON.parse(readFileSync(path.join(base, dir, 'package.json'), 'utf8')) as Pkg;
    } catch {
      errors.push(`${kind}s/${dir}: missing or unreadable package.json`);
      continue;
    }
    const pkgName = typeof pkg.name === 'string' ? pkg.name : '';
    if (!pkgName.startsWith(prefix)) {
      errors.push(`${kind}s/${dir}: package name "${pkgName}" must start with ${prefix}`);
      continue;
    }
    const id = pkgName.slice(prefix.length);
    const first = seen.get(id);
    if (first !== undefined) {
      errors.push(`duplicate ${kind} id "${id}" (${kind}s/${first} and ${kind}s/${dir})`);
      continue;
    }
    seen.set(id, dir);
    if (id !== dir) {
      errors.push(`${kind}s/${dir}: folder name must equal the id "${id}"`);
      continue;
    }
    const dashName = pkg.dash?.name;
    entries.push({ id, name: typeof dashName === 'string' && dashName ? dashName : id });
  }
  return entries;
}

const HEADER = '// GENERATED by tools/gen-registry.ts. Do not edit; run `pnpm gen`.\n';
const q = (s: string): string => JSON.stringify(s);
const ident = (id: string): string => `m_${id.replace(/-/g, '_')}`;
// generated files sit at apps/<app>/src/generated/
const UP = '../../../..';

function serverFile(mods: Entry[]): string {
  const items = mods.map((m) => `  () => import(${q(`${UP}/modules/${m.id}/server/index.js`)}),\n`).join('');
  return `${HEADER}import type { ModuleServer } from '@dash/contract';

export const serverModules: Array<() => Promise<{ default: ModuleServer }>> = [
${items}];
`;
}

function webModulesFile(mods: Entry[]): string {
  const imports = mods.map((m) => `import ${ident(m.id)} from ${q(`${UP}/modules/${m.id}/manifest.js`)};\n`).join('');
  const items = mods
    .map(
      (m) =>
        `  ${q(m.id)}: { manifest: ${ident(m.id)}, load: () => import(${q(`${UP}/modules/${m.id}/client/index.js`)}) },\n`,
    )
    .join('');
  return `${HEADER}import type { ModuleClient, ModuleId, ModuleManifest } from '@dash/contract';
${imports}
export const clientModules: Record<
  ModuleId,
  { manifest: ModuleManifest; load: () => Promise<{ default: ModuleClient }> }
> = {
${items}};
`;
}

function themesFile(themes: Entry[]): string {
  const items = themes
    .map(
      (t) =>
        `  ${q(t.id)}: {\n    load: () => import(${q(`${UP}/themes/${t.id}/theme.js`)}),\n    meta: { id: ${q(t.id)}, name: ${q(t.name)} },\n  },\n`,
    )
    .join('');
  return `${HEADER}import type { ThemeId, ThemeManifest } from '@dash/contract';

export const themes: Record<
  ThemeId,
  { load: () => Promise<{ default: ThemeManifest }>; meta: { id: string; name: string } }
> = {
${items}};
`;
}

function write(file: string, content: string): void {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
}

export function generate(rootDir: string): GenResult {
  const errors: string[] = [];
  const mods = scan(rootDir, 'module', errors);
  const themes = scan(rootDir, 'theme', errors);
  if (errors.length > 0) return { exitCode: 1, messages: errors };
  write(path.join(rootDir, 'apps/server/src/generated/modules.ts'), serverFile(mods));
  write(path.join(rootDir, 'apps/web/src/generated/modules.ts'), webModulesFile(mods));
  write(path.join(rootDir, 'apps/web/src/generated/themes.ts'), themesFile(themes));
  return {
    exitCode: 0,
    messages: [`generated registries: ${mods.length} module(s), ${themes.length} theme(s)`],
  };
}

export const REPO_ROOT = path.resolve(import.meta.dirname, '..');

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const res = generate(REPO_ROOT);
  for (const m of res.messages) (res.exitCode === 0 ? console.log : console.error)(m);
  process.exitCode = res.exitCode;
}
